using OneGame.Host;
using System.Security;
using System.Text;
using System.Text.Json;

namespace OneGame.Cli.Verbs;

/// <summary>What a web export produced.</summary>
/// <param name="Folder">The folder to serve: <c>index.html</c>, the script modules and <c>_framework</c>.</param>
/// <param name="Files">Number of files, not counting the precompressed copies.</param>
/// <param name="Bytes">Their total size.</param>
/// <param name="WireBytes">What a browser downloads from a server that sends the Brotli copies.</param>
/// <param name="Configuration">Debug (development tools included) or Release.</param>
/// <param name="Seconds">How long the export took.</param>
internal sealed record WebExportResult(string Folder, int Files, long Bytes, long WireBytes, string Configuration, double Seconds);

/// <summary>
/// Builds a game for the browser. A game's own project is a desktop program; the browser needs the WebAssembly SDK, so the export writes a small
/// wrapper project that compiles the game's own files, embedded resources and references against it and publishes that.
/// </summary>
internal static class WebExport
{
    private static readonly string[] PageFiles = ["index.html", "boot.mjs", "onegame-platform.js", "onegame-audio.js"];

    private const string ContentStarter = """
        // <auto-generated> Written by 'onegame export --target web'. </auto-generated>
        #nullable enable
        namespace OneGameWebExport;

        internal static class WebContent
        {
            [System.Runtime.CompilerServices.ModuleInitializer]
            internal static void Unpack()
            {
                var assembly = typeof(WebContent).Assembly;
                const string prefix = "onegame-content/";
                foreach (var name in assembly.GetManifestResourceNames())
                {
                    if (!name.StartsWith(prefix, System.StringComparison.Ordinal))
                    {
                        continue;
                    }

                    var target = System.IO.Path.Combine(System.AppContext.BaseDirectory, name.Substring(prefix.Length));
                    System.IO.Directory.CreateDirectory(System.IO.Path.GetDirectoryName(target)!);
                    using var source = assembly.GetManifestResourceStream(name)!;
                    using var file = System.IO.File.Create(target);
                    source.CopyTo(file);
                }
            }
        }
        """;

    // Properties of the game's project that the wrapper repeats: the ones that change how its code compiles. A game that sets one in its csproj
    // (unsafe code for [JSImport], a shader namespace) builds the same way here as on the desktop.
    private static readonly string[] CarriedProperties =
    [
        "AllowUnsafeBlocks", "NoWarn", "WarningsNotAsErrors", "WarningsAsErrors", "DefineConstants", "LangVersion", "GenerateDocumentationFile",
        "OneShaderTargets", "OneShaderNamespace", "OneShaderAccessibility", "OneShaderEnable16BitTypes", "OneShaderDebugInfo",
        "OneShaderOptimize", "OneShaderDefines", "OneShaderIncludeDirectories", "OneShaderMaxVariants",
    ];

    // Item metadata the shader compiler reads.
    private static readonly string[] ShaderMetadata =
        ["EntryPoints", "Defines", "IncludeDirectories", "Targets", "Enable16BitTypes", "DebugInfo", "Optimize", "Namespace", "Accessibility", "ClassName", "Axes", "MaxVariants"];

    private static readonly string[] EngineReferences = ["OneGame.Host", "OneGame.Core", "OneGame.UI", "OneGame.Generators", "OneGame.Live"];

    public static WebExportResult Export(ProjectRef project, bool dev, string outFolder)
    {
        var clock = System.Diagnostics.Stopwatch.StartNew();
        var configuration = dev ? "Debug" : "Release";
        // The shader items come from build files a restore writes (the shader package's targets), so a game that was never built would
        // list none and its wrapper would have no shaders. Restoring first makes the first export of a fresh checkout read what a build would.
        var restore = Proc.Run(Proc.Dotnet, ["restore", project.File, "-nologo", "-v", "quiet", "-clp:NoSummary", $"-p:OneGameDev={(dev ? "true" : "false")}", $"-p:Configuration={configuration}"], project.Directory);
        if (restore.ExitCode != 0)
        {
            throw new CliException(ExitCodes.BuildFailed, "bad_project", $"Could not restore {project.File}: {restore.Output.Trim()} {restore.Error.Trim()}");
        }

        var query = Proc.Run(Proc.Dotnet, ["msbuild", project.File, $"-getItem:Compile,EmbeddedResource,ProjectReference,PackageReference,OneShader,OneShaderVariant,AdditionalFiles,InternalsVisibleTo", $"-getProperty:OneGameRoot,AssemblyName,RootNamespace,OneGameVersion,{string.Join(',', CarriedProperties)}", $"-p:OneGameDev={(dev ? "true" : "false")}", $"-p:Configuration={configuration}", "-nologo"], project.Directory);
        if (query.ExitCode != 0)
        {
            throw new CliException(ExitCodes.BuildFailed, "bad_project", $"Could not read {project.File}: {query.Output.Trim()} {query.Error.Trim()}");
        }

        using var doc = JsonDocument.Parse(query.Output);
        var props = doc.RootElement.GetProperty("Properties");
        var root = props.GetProperty("OneGameRoot").GetString();
        var packageMode = string.IsNullOrEmpty(root);
        var version = props.GetProperty("OneGameVersion").GetString();
        if (packageMode && string.IsNullOrEmpty(version))
        {
            throw new CliException(ExitCodes.BuildFailed, "bad_project", "The project sets neither OneGameRoot nor OneGameVersion: it is not a onegame game. Create one with 'onegame new'.");
        }

        root = packageMode ? "" : Path.GetFullPath(root!, project.Directory);
        var assembly = props.GetProperty("AssemblyName").GetString() ?? project.Name;
        var ns = props.GetProperty("RootNamespace").GetString() ?? assembly;
        var items = doc.RootElement.GetProperty("Items");
        var projectDir = Path.GetFullPath(project.Directory) + Path.DirectorySeparatorChar;
        var build = packageMode ? null : Path.Combine(root, "build") + Path.DirectorySeparatorChar;

        var xml = new StringBuilder();
        xml.AppendLine("<Project Sdk=\"Microsoft.NET.Sdk.WebAssembly\">");
        xml.AppendLine("  <PropertyGroup>");
        if (!packageMode)
        {
            xml.AppendLine($"    <OneGameRoot>{Esc(root)}{Path.DirectorySeparatorChar}</OneGameRoot>");
        }
        else
        {
            // What build/Game.targets sets for a game, for a game that has no engine checkout to import it from.
            xml.AppendLine("    <TargetFramework>net10.0</TargetFramework>");
            xml.AppendLine("    <LangVersion>latest</LangVersion>");
            xml.AppendLine("    <Nullable>enable</Nullable>");
            xml.AppendLine("    <ImplicitUsings>disable</ImplicitUsings>");
            xml.AppendLine("    <TreatWarningsAsErrors>true</TreatWarningsAsErrors>");
            xml.AppendLine("    <AnalysisLevel>latest-recommended</AnalysisLevel>");
            xml.AppendLine("    <InvariantGlobalization>true</InvariantGlobalization>");
            xml.AppendLine("    <Deterministic>true</Deterministic>");
            xml.AppendLine("    <JsonSerializerIsReflectionEnabledByDefault>false</JsonSerializerIsReflectionEnabledByDefault>");
            xml.AppendLine("    <OutputType>Exe</OutputType>");
            // A Directory.Packages.props above the game would otherwise apply to this project too; the versions below are already resolved.
            xml.AppendLine("    <ManagePackageVersionsCentrally>false</ManagePackageVersionsCentrally>");
            if (dev)
            {
                xml.AppendLine("    <DefineConstants>$(DefineConstants);ONEGAME_DEV</DefineConstants>");
            }
        }

        xml.AppendLine($"    <AssemblyName>{Esc(assembly)}</AssemblyName>");
        xml.AppendLine($"    <RootNamespace>{Esc(ns)}</RootNamespace>");
        xml.AppendLine("    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>");
        xml.AppendLine("    <EnableDefaultEmbeddedResourceItems>false</EnableDefaultEmbeddedResourceItems>");
        xml.AppendLine("    <WasmEnableWebcil>false</WasmEnableWebcil>");
        xml.AppendLine($"    <OneGameDev>{(dev ? "true" : "false")}</OneGameDev>");
        foreach (var name in CarriedProperties)
        {
            if (props.TryGetProperty(name, out var value) && value.GetString() is { Length: > 0 } text)
            {
                // The shader item list is written below, from the project's own evaluation, so the wrapper must not glob again.
                xml.AppendLine($"    <{name}>{Esc(name == "OneShaderIncludeDirectories" ? AbsoluteList(text, projectDir) : text)}</{name}>");
            }
        }

        // The browser takes WGSL; a game that compiled only for the desktop gets it added.
        var targets = props.TryGetProperty("OneShaderTargets", out var t) && t.GetString() is { Length: > 0 } tt ? tt : "SpirV";
        if (!targets.Split(';', StringSplitOptions.RemoveEmptyEntries).Contains("Wgsl", StringComparer.OrdinalIgnoreCase))
        {
            xml.AppendLine($"    <OneShaderTargets>{Esc(targets)};Wgsl</OneShaderTargets>");
        }

        xml.AppendLine("    <EnableDefaultOneShaderItems>false</EnableDefaultOneShaderItems>");
        xml.AppendLine("  </PropertyGroup>");
        if (!packageMode)
        {
            xml.AppendLine("  <Import Project=\"$(OneGameRoot)build/Game.targets\" />");
        }

        xml.AppendLine("  <ItemGroup>");
        foreach (var item in items.GetProperty("Compile").EnumerateArray())
        {
            var full = Full(item, project.Directory);
            if ((build is not null && full.StartsWith(build, StringComparison.Ordinal)) || IsGenerated(full, projectDir))
            {
                continue;
            }

            xml.AppendLine($"    <Compile Include=\"{Esc(full)}\" />");
        }

        foreach (var item in items.GetProperty("EmbeddedResource").EnumerateArray())
        {
            var full = Full(item, project.Directory);
            if (IsGenerated(full, projectDir))
            {
                continue;
            }

            var logical = item.TryGetProperty("LogicalName", out var l) && l.GetString() is { Length: > 0 } name ? $" LogicalName=\"{Esc(name)}\"" : "";
            xml.AppendLine($"    <EmbeddedResource Include=\"{Esc(full)}\"{logical} />");
        }

        // The game's HLSL: compiled by OneShader.Build (the game's own package reference, passed on below) with the game's own settings.
        foreach (var item in items.GetProperty("OneShader").EnumerateArray())
        {
            xml.AppendLine($"    <OneShader Include=\"{Esc(Full(item, project.Directory))}\"{ShaderAttributes(item, projectDir)} />");
        }

        foreach (var item in items.GetProperty("OneShaderVariant").EnumerateArray())
        {
            var shader = item.TryGetProperty("Shader", out var sh) ? sh.GetString() : null;
            var shaderFull = string.IsNullOrEmpty(shader) ? "" : Path.GetFullPath(shader, projectDir);
            xml.AppendLine($"    <OneShaderVariant Include=\"{Esc(item.GetProperty("Identity").GetString()!)}\" Shader=\"{Esc(shaderFull)}\"{ShaderAttributes(item, projectDir)} />");
        }

        foreach (var item in items.GetProperty("AdditionalFiles").EnumerateArray())
        {
            var full = Full(item, project.Directory);
            if (!IsGenerated(full, projectDir))
            {
                xml.AppendLine($"    <AdditionalFiles Include=\"{Esc(full)}\" />");
            }
        }

        foreach (var item in items.GetProperty("InternalsVisibleTo").EnumerateArray())
        {
            xml.AppendLine($"    <InternalsVisibleTo Include=\"{Esc(item.GetProperty("Identity").GetString()!)}\" />");
        }

        foreach (var item in items.GetProperty("ProjectReference").EnumerateArray())
        {
            var full = Full(item, project.Directory);
            if (Array.IndexOf(EngineReferences, Path.GetFileNameWithoutExtension(full)) >= 0)
            {
                continue;
            }

            xml.AppendLine($"    <ProjectReference Include=\"{Esc(full)}\" />");
        }

        // The game's package references travel too (the shader compiler is one). A game on the SDK package pins the engine libraries at its own
        // version; a game in an engine checkout takes its versions from the checkout's central list, so only an explicit override is repeated.
        foreach (var item in items.GetProperty("PackageReference").EnumerateArray())
        {
            var id = item.GetProperty("Identity").GetString()!;
            var ver = item.TryGetProperty("VersionOverride", out var vo) && vo.GetString() is { Length: > 0 } v1 ? v1 : item.TryGetProperty("Version", out var vv) ? vv.GetString() : null;
            var attr = string.IsNullOrEmpty(ver) ? "" : packageMode ? $" Version=\"{Esc(ver)}\"" : $" VersionOverride=\"{Esc(ver)}\"";
            foreach (var meta in new[] { "PrivateAssets", "IncludeAssets", "ExcludeAssets" })
            {
                if (item.TryGetProperty(meta, out var mv) && mv.GetString() is { Length: > 0 } m)
                {
                    attr += $" {meta}=\"{Esc(m)}\"";
                }
            }

            xml.AppendLine($"    <PackageReference Include=\"{Esc(id)}\"{attr} />");
        }

        // The game's content folders (fonts, art, data) travel inside the program and are written to its file system before anything runs: the
        // browser has no folder beside the program, and the default asset and font readers look for one, as in every other export. A game that
        // already embeds a file under the same name keeps its own copy.
        var content = Path.Combine(projectDir, "obj", "onegame-web", "content");
        if (Directory.Exists(content))
        {
            Directory.Delete(content, true);
        }

        Directory.CreateDirectory(content);
        ExportAssets.Copy(projectDir, content, [], []);
        var own = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in items.GetProperty("EmbeddedResource").EnumerateArray())
        {
            own.Add(item.TryGetProperty("LogicalName", out var l) && l.GetString() is { Length: > 0 } name ? name : item.GetProperty("Identity").GetString()!);
        }

        var shipped = new List<string>();
        foreach (var file in Directory.EnumerateFiles(content, "*", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
        {
            var relative = Path.GetRelativePath(content, file).Replace('\\', '/');
            if (own.Contains(relative))
            {
                continue;
            }

            shipped.Add(relative);
            xml.AppendLine($"    <EmbeddedResource Include=\"{Esc(file)}\" LogicalName=\"onegame-content/{Esc(relative)}\" />");
        }

        var starter = Path.Combine(projectDir, "obj", "onegame-web", "WebContent.g.cs");
        File.WriteAllText(starter, ContentStarter);
        xml.AppendLine($"    <Compile Include=\"{Esc(starter)}\" />");

        // The page: the host's script modules and a start page, served beside the runtime files. They travel inside the tool.
        var page = Path.Combine(projectDir, "obj", "onegame-web", "page");
        Directory.CreateDirectory(page);
        foreach (var name in PageFiles)
        {
            using var stream = typeof(WebExport).Assembly.GetManifestResourceStream("web/" + name) ?? throw new CliException(ExitCodes.BuildFailed, "missing_resource", $"The tool lacks its embedded web file {name}.");
            using var file = File.Create(Path.Combine(page, name));
            stream.CopyTo(file);
            xml.AppendLine($"    <Content Include=\"{Esc(Path.Combine(page, name))}\" Link=\"wwwroot/{name}\" />");
        }
        xml.AppendLine("  </ItemGroup>");
        xml.AppendLine("</Project>");

        var work = Path.Combine(projectDir, "obj", "onegame-web");
        Directory.CreateDirectory(work);
        var wrapper = Path.Combine(work, assembly + ".Web.csproj");
        File.WriteAllText(wrapper, xml.ToString());

        var temp = Path.Combine(work, "publish");
        if (Directory.Exists(temp))
        {
            Directory.Delete(temp, true);
        }

        var run = Proc.Run(Proc.Dotnet, ["publish", wrapper, "-c", configuration, "-o", temp, "--nologo", "-v", "q", "-clp:NoSummary", "-p:GenerateFullPaths=true"], work);
        if (run.ExitCode != 0)
        {
            var errors = BuildOutput.Parse(run.Output + "\n" + run.Error).Where(d => d.Severity == "error").Take(8)
                .Select(d => d.File is null ? $"{d.Code}: {d.Message}" : $"{d.File}({d.Line}): {d.Code}: {d.Message}");
            var text = string.Join(" | ", errors);
            if (text.Length == 0)
            {
                text = string.Join(" | ", (run.Output + "\n" + run.Error).Split('\n').Select(l => l.Trim()).Where(l => l.Length > 0).TakeLast(6));
            }

            throw new CliException(ExitCodes.BuildFailed, "publish_failed", $"dotnet publish for the browser failed (exit {run.ExitCode}): {text}");
        }

        var www = Path.Combine(temp, "wwwroot");
        if (Directory.Exists(outFolder))
        {
            Directory.Delete(outFolder, true);
        }

        Directory.CreateDirectory(outFolder);
        long bytes = 0, wire = 0;
        var files = 0;
        foreach (var file in Directory.GetFiles(www, "*", SearchOption.AllDirectories))
        {
            var relative = Path.GetRelativePath(www, file);
            var target = Path.Combine(outFolder, relative);
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.Copy(file, target);
            var length = new FileInfo(file).Length;
            if (file.EndsWith(".br", StringComparison.Ordinal) || file.EndsWith(".gz", StringComparison.Ordinal))
            {
                continue;
            }

            files++;
            bytes += length;
            var br = file + ".br";
            wire += File.Exists(br) ? new FileInfo(br).Length : length;
        }

        Fingerprint(outFolder);
        return new WebExportResult(outFolder, files, bytes, wire, configuration, clock.Elapsed.TotalSeconds);
    }

    // The scripts a page loads by a fixed name: a CDN or the browser's cache that kept the old file would pair a new program with an old
    // loader. Each import in boot.mjs, and boot.mjs in index.html, gets ?v=<hash of that file's content>, so a changed file is a new URL. The
    // runtime's own files already carry a hash in their names (and dotnet.js names them).
    private static readonly (string Import, string File)[] VersionedImports =
    [
        ("./_framework/dotnet.js", "_framework/dotnet.js"),
        ("./_content/RecursiveAI.OneGpu.WebGpu/onegpu.js", "_content/RecursiveAI.OneGpu.WebGpu/onegpu.js"),
        ("./onegame-platform.js", "onegame-platform.js"),
        ("./onegame-audio.js", "onegame-audio.js"),
    ];

    /// <summary>Adds content hashes to the script URLs of an exported folder and rewrites the Brotli and gzip copies of the files it changes.</summary>
    /// <param name="folder">The export folder.</param>
    internal static void Fingerprint(string folder)
    {
        var boot = Path.Combine(folder, "boot.mjs");
        var index = Path.Combine(folder, "index.html");
        if (!File.Exists(boot) || !File.Exists(index))
        {
            return;
        }

        var text = File.ReadAllText(boot);
        foreach (var (import, file) in VersionedImports)
        {
            var path = Path.Combine(folder, file);
            if (File.Exists(path))
            {
                text = text.Replace($"'{import}'", $"'{import}?v={Tag(path)}'", StringComparison.Ordinal);
            }
        }

        WriteWithCopies(boot, text);
        var page = File.ReadAllText(index).Replace("src=\"./boot.mjs\"", $"src=\"./boot.mjs?v={Tag(boot)}\"", StringComparison.Ordinal);
        WriteWithCopies(index, page);
    }

    private static string Tag(string path) => Convert.ToHexStringLower(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(path)))[..10];

    private static void WriteWithCopies(string path, string text)
    {
        var data = new UTF8Encoding(false).GetBytes(text);
        File.WriteAllBytes(path, data);
        foreach (var (ext, make) in new (string, Func<Stream, Stream>)[]
        {
            (".br", s => new System.IO.Compression.BrotliStream(s, System.IO.Compression.CompressionLevel.SmallestSize)),
            (".gz", s => new System.IO.Compression.GZipStream(s, System.IO.Compression.CompressionLevel.SmallestSize)),
        })
        {
            if (!File.Exists(path + ext))
            {
                continue;
            }

            using var output = File.Create(path + ext);
            using (var packed = make(output))
            {
                packed.Write(data);
            }
        }
    }

    private static string ShaderAttributes(JsonElement item, string projectDir)
    {
        var text = new StringBuilder();
        foreach (var name in ShaderMetadata)
        {
            if (!item.TryGetProperty(name, out var v) || v.GetString() is not { Length: > 0 } value)
            {
                continue;
            }

            text.Append($" {name}=\"{Esc(name == "IncludeDirectories" ? AbsoluteList(value, projectDir) : value)}\"");
        }

        return text.ToString();
    }

    // The shader compiler resolves include folders against the project it builds, which is the wrapper in obj; the game's are relative to its own folder.
    private static string AbsoluteList(string list, string projectDir) =>
        string.Join(';', list.Split(';', StringSplitOptions.RemoveEmptyEntries).Select(d => Path.GetFullPath(d, projectDir)));

    private static string Full(JsonElement item, string directory) => Path.GetFullPath(item.GetProperty("FullPath").GetString() ?? item.GetProperty("Identity").GetString()!, directory);

    private static bool IsGenerated(string path, string projectDir) =>
        path.StartsWith(projectDir + "obj" + Path.DirectorySeparatorChar, StringComparison.Ordinal) || path.StartsWith(projectDir + "bin" + Path.DirectorySeparatorChar, StringComparison.Ordinal);

    private static string Esc(string text) => SecurityElement.Escape(text) ?? "";
}
