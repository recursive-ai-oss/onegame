using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace OneGame.Generators;

/// <summary>Generates everything behind entities, synced structs and hot-data tables. See docs/interfaces/entity-sync.md for the generated surface.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class EntityGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor[] AllRules =
    [
        Rules.FloatInState, Rules.FloatInSim, Rules.UnorderedIteration, Rules.Clock, Rules.Threads, Rules.InputOutput,
        Rules.UnnamedRandom, Rules.ViewWrites, Rules.NoCodec, Rules.EntityShape, Rules.TooManyProperties, Rules.PropertyShape,
        Rules.CommandShape, Rules.MigrationShape,
    ];

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var entities = context.SyntaxProvider.ForAttributeWithMetadataName(
            "OneGame.Core.EntityAttribute", static (node, _) => node is ClassDeclarationSyntax, EntityEmitter.Build)
            .WithTrackingName("Entity");
        var structs = context.SyntaxProvider.ForAttributeWithMetadataName(
            "OneGame.Core.SyncedStructAttribute", static (node, _) => node is StructDeclarationSyntax, ValueEmitters.BuildStruct);
        var tables = context.SyntaxProvider.ForAttributeWithMetadataName(
            "OneGame.Core.HotDataAttribute", static (node, _) => node is StructDeclarationSyntax, ValueEmitters.BuildTable);

        context.RegisterSourceOutput(entities, Emit);
        context.RegisterSourceOutput(structs, Emit);
        context.RegisterSourceOutput(tables, Emit);

        var registrations = entities
            .Select(static (r, _) => r.Registration)
            .Where(static r => r is not null)
            .Collect()
            .Combine(context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "Assembly"));
        context.RegisterSourceOutput(registrations, static (spc, input) =>
        {
            var (items, assembly) = input;
            if (items.Length == 0)
            {
                return;
            }

            var s = new Src();
            s.Line("// <auto-generated/>");
            s.Line("#nullable enable");
            s.Open("namespace OneGame.Generated." + Sanitize(assembly));
            s.Line("/// <summary>The entity types declared in this assembly.</summary>");
            s.Open("public static class EntityTypes");
            s.Line("/// <summary>Registers this assembly's entities so a world can create them while restoring a snapshot.</summary>");
            s.Open("public static void Register(global::OneGame.Core.EntityRegistry registry)");
            foreach (var r in items.OrderBy(i => i!.TypeName, System.StringComparer.Ordinal))
            {
                s.Line($"registry.Add({EmitUtil.Hex(r!.TypeId)}, {EmitUtil.Literal(r.DisplayName)}, static () => new {r.TypeName}());");
            }

            s.Close();
            s.Close();
            s.Close();
            spc.AddSource("OneGame.EntityTypes.g.cs", s.ToString());
        });
    }

    private static string Sanitize(string name)
    {
        var sb = new StringBuilder();
        foreach (var c in name)
        {
            sb.Append(char.IsLetterOrDigit(c) ? c : '_');
        }

        return sb.Length > 0 && char.IsDigit(sb[0]) ? "_" + sb : sb.ToString();
    }

    private static void Emit(SourceProductionContext spc, GenResult result)
    {
        foreach (var d in result.Diagnostics)
        {
            spc.ReportDiagnostic(d.ToDiagnostic(AllRules.First(r => r.Id == d.Id)));
        }

        if (result.Source is not null && result.HintName is not null)
        {
            spc.AddSource(result.HintName, result.Source);
        }
    }
}
