// Generates the Wayland protocol tables the platform layer needs from the protocol XML files:
// interface and message descriptions (for libwayland-client's marshalling), opcode constants and enum values.
//
// Usage: dotnet run --project tools/WaylandGen -- <protocol dir> <output .cs file>
using System.Text;
using System.Xml.Linq;

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: WaylandGen <protocol dir> <output file>");
    return 1;
}

var files = Directory.GetFiles(args[0], "*.xml").OrderBy(f => f, StringComparer.Ordinal).ToArray();
var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// Produced by tools/WaylandGen from the protocol XML files in tools/WaylandGen/protocols:");
foreach (var f in files)
{
    sb.AppendLine("//   " + Path.GetFileName(f));
}

sb.AppendLine("// Do not edit; rerun the tool instead.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("namespace OneGame.Platform;");
sb.AppendLine();

var all = new List<string>();
var body = new StringBuilder();
foreach (var file in files)
{
    var doc = XDocument.Load(file);
    foreach (var iface in doc.Root!.Elements("interface"))
    {
        var name = (string)iface.Attribute("name")!;
        var version = (int)iface.Attribute("version")!;
        var cls = Pascal(name);
        all.Add(cls);

        var requests = iface.Elements("request").ToList();
        var events = iface.Elements("event").ToList();

        body.AppendLine($"/// <summary>Opcodes, enum values and the message table of <c>{name}</c> (version {version}).</summary>");
        body.AppendLine($"internal static class {cls}");
        body.AppendLine("{");
        body.AppendLine($"    /// <summary>The interface name.</summary>");
        body.AppendLine($"    public const string Name = \"{name}\";");
        body.AppendLine($"    /// <summary>The highest version this table knows.</summary>");
        body.AppendLine($"    public const int Version = {version};");
        body.AppendLine();
        body.AppendLine("    /// <summary>Request opcodes.</summary>");
        body.AppendLine("    public static class Request");
        body.AppendLine("    {");
        for (var i = 0; i < requests.Count; i++)
        {
            body.AppendLine($"        public const int {Pascal((string)requests[i].Attribute("name")!)} = {i};");
        }

        body.AppendLine("    }");
        body.AppendLine();
        body.AppendLine("    /// <summary>Event opcodes.</summary>");
        body.AppendLine("    public static class Event");
        body.AppendLine("    {");
        for (var i = 0; i < events.Count; i++)
        {
            body.AppendLine($"        public const int {Pascal((string)events[i].Attribute("name")!)} = {i};");
        }

        body.AppendLine("    }");

        foreach (var en in iface.Elements("enum"))
        {
            body.AppendLine();
            body.AppendLine($"    /// <summary>Values of the <c>{(string)en.Attribute("name")!}</c> enum.</summary>");
            body.AppendLine($"    public static class {Pascal((string)en.Attribute("name")!)}Enum");
            body.AppendLine("    {");
            foreach (var entry in en.Elements("entry"))
            {
                var ename = Pascal((string)entry.Attribute("name")!);
                if (char.IsDigit(ename[0]))
                {
                    ename = "V" + ename;
                }

                var value = (string)entry.Attribute("value")!;
                var parsed = value.StartsWith("0x", StringComparison.Ordinal) ? Convert.ToUInt32(value[2..], 16) : uint.Parse(value);
                body.AppendLine($"        public const uint {ename} = {parsed};");
            }

            body.AppendLine("    }");
        }

        body.AppendLine();
        body.AppendLine("    /// <summary>The message table.</summary>");
        body.AppendLine("    public static readonly WlInterfaceInfo Info = new(");
        body.AppendLine($"        \"{name}\",");
        body.AppendLine($"        {version},");
        body.AppendLine("        [");
        foreach (var r in requests)
        {
            body.AppendLine("            " + Message(r) + ",");
        }

        body.AppendLine("        ],");
        body.AppendLine("        [");
        foreach (var ev in events)
        {
            body.AppendLine("            " + Message(ev) + ",");
        }

        body.AppendLine("        ]);");
        body.AppendLine("}");
        body.AppendLine();
    }
}

sb.AppendLine("/// <summary>Every interface in the generated tables.</summary>");
sb.AppendLine("internal static class WaylandProtocols");
sb.AppendLine("{");
sb.AppendLine("    /// <summary>All interface descriptions.</summary>");
sb.AppendLine("    public static readonly WlInterfaceInfo[] All =");
sb.AppendLine("    [");
foreach (var c in all)
{
    sb.AppendLine($"        {c}.Info,");
}

sb.AppendLine("    ];");
sb.AppendLine("}");
sb.AppendLine();
sb.Append(body);
File.WriteAllText(args[1], sb.ToString().Replace("\r\n", "\n"));
Console.WriteLine($"{all.Count} interfaces from {files.Length} files");
return 0;

static string Pascal(string s) => string.Concat(s.Split('_').Where(p => p.Length > 0).Select(p => char.ToUpperInvariant(p[0]) + p[1..]));

// One message as a C# initializer: its name, libwayland signature string and, per argument, the interface it names (or null).
static string Message(XElement m)
{
    var sig = new StringBuilder();
    var types = new List<string>();
    var since = m.Attribute("since") is { } s ? int.Parse(s.Value) : 1;
    if (since > 1)
    {
        sig.Append(since);
    }

    foreach (var arg in m.Elements("arg"))
    {
        var type = (string)arg.Attribute("type")!;
        var iface = (string?)arg.Attribute("interface");
        var nullable = (string?)arg.Attribute("allow-null") == "true";
        if (type == "new_id" && iface is null)
        {
            // A new_id with no fixed interface is sent as interface name, version and id (wl_registry.bind).
            sig.Append("sun");
            types.Add("null");
            types.Add("null");
            types.Add("null");
            continue;
        }

        if (nullable)
        {
            sig.Append('?');
        }

        sig.Append(type switch
        {
            "int" => 'i',
            "uint" => 'u',
            "fixed" => 'f',
            "string" => 's',
            "object" => 'o',
            "new_id" => 'n',
            "array" => 'a',
            "fd" => 'h',
            _ => throw new InvalidOperationException("unknown argument type " + type),
        });
        types.Add(iface is not null && (type is "object" or "new_id") ? $"\"{iface}\"" : "null");
    }

    return $"new(\"{(string)m.Attribute("name")!}\", \"{sig}\", [{string.Join(", ", types)}])";
}
